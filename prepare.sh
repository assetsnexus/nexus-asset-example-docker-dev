      type: redis
      enabled: ${REG_DB}
      hosts:
        - host: redis
          port: 6379
          password: "\${REDIS_PASSWORD}"
      connectionMode: round_robin
      redis:
        db: 0
        keyPrefix: anx:
EOF
echo "  wrote data/config/database.yaml (registry-db=${REG_DB})"

if [[ ! -f data/config/general.yml ]]; then
