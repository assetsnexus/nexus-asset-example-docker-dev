    echo '    secureJsonData:'
    echo "      password: ${POSTGRES_PASSWORD}"
    echo '    jsonData:'
    echo "      database: ${POSTGRES_DATABASE:-anx_assets}"
    echo '      sslmode: disable'
    echo '      postgresVersion: 1600'
  fi
  if has_profile logs; then
    echo '  - name: Loki'
    echo '    type: loki'
    echo '    access: proxy'
    echo '    url: http://loki:3100'
    echo '    isDefault: false'
  fi
} > "$DS_FILE"

