  volumes/victoriametrics \
  volumes/postgres \
  volumes/mongodb/data \
  volumes/mongodb/config \
  volumes/redis \
  volumes/grafana \
  volumes/prometheus \
  volumes/mqtt/data \
  volumes/mqtt/log \
  volumes/nodered \
  volumes/loki
echo "  ensured volumes/{victoriametrics,postgres,mongodb,redis,grafana,prometheus,mqtt,nodered,loki}"

